export const normalizeInspectionLocationKey = (value) =>
  String(value || '')
    .trim()
    .toLowerCase()

export const dedupeLocationOptions = (rows = []) => {
  const byKey = new Map()
  ;(Array.isArray(rows) ? rows : []).forEach((row) => {
    const value = String(row?.value || row?.title || '').trim()
    if (!value) return
    const key = normalizeInspectionLocationKey(value)
    if (byKey.has(key)) return
    byKey.set(key, {
      ...row,
      value,
      title: String(row?.title || value).trim(),
      description: String(row?.description || '').trim(),
      subLocations: Array.isArray(row?.subLocations)
        ? dedupeLocationOptions(row.subLocations).map((sub) => ({
            value: sub.value,
            title: sub.title,
            description: sub.description,
          }))
        : [],
    })
  })
  return Array.from(byKey.values())
}

export const getInspectionLocationDefaults = (inspectionType) => {
  const key = normalizeInspectionLocationKey(inspectionType)
  return dedupeLocationOptions(LOCATION_DEFAULTS_BY_TYPE[key] || sharedSiteLocations)
}
